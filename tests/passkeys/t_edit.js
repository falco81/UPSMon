  await p.click(pen); await p.keyboard.type('Můj iPad'); await p.keyboard.press('Enter'); await p.waitForTimeout(1200);
  const ent = await nm();
  check('Enter: renamed', ent === 'Můj iPad' && (await p.textContent(row + ' td.pk-name')).trim() === 'Můj iPad', ent);
  await p.click(pen); await p.keyboard.type('Pracovní'); await p.click(pen); await p.waitForTimeout(1200);
  check('the pencil again: kept', (await nm()) === 'Pracovní', await nm());
  await p.click(pen); await p.keyboard.type('Domácí'); await p.mouse.click(300, 40); await p.waitForTimeout(1200);
  check('clicked elsewhere: kept', (await nm()) === 'Domácí', await nm());
