const { chromium } = require('playwright');
const S = '/tmp/claude-0/-home-user-UPSMon/eb6ab9f9-d3d4-5653-939f-615b11af19f7/scratchpad/';
let ok = 0, bad = 0;
const check = (n, c, g) => { if (c) { ok++; console.log('OK   ' + n); } else { bad++; console.log('FAIL ' + n + '  -> ' + JSON.stringify(g)); } };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1500, height: 950 } });
  await ctx.addCookies([{ name: 'upsmon_lang', value: process.argv[2] || 'en', url: 'http://localhost:8080' }]);
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
  const asked = []; p.on('request', r => { if (/api=load/.test(r.url())) asked.push(r.url().replace(/.*api=/, '')); });
  await p.goto('http://localhost:8080/settings/');
  await p.fill('#in-name', 'admin'); await p.fill('#in-pass', 'secret123'); await p.click('#in-go');
  await p.waitForSelector('#ctl-nav');
  await p.evaluate(() => api('settings', {settings: {load_meter: 0}}));
  await p.reload(); asked.length = 0; await p.waitForSelector('#ctl-nav'); await p.waitForTimeout(1500);
  check('off (the default): nothing in the header', !(await p.$('#hload')), null);
  check('off: the page does not ask', asked.length === 0, asked);
  const r = await p.evaluate(() => api('load').then(() => 'went', e => e.message));
  check('off: the API refuses', /not shown here/.test(r), r);
  await p.evaluate(() => api('settings', {settings: {load_meter: 1}}));
  await p.reload(); await p.waitForSelector('#ctl-nav'); await p.waitForTimeout(4500);
  check('on: the numbers in the header', await p.isVisible('#hload') && (await p.$$('#hload .hl')).length >= 2, await p.innerHTML('#hload').catch(() => ''));
  const d = await p.evaluate(() => api('load'));
  check('the summary: cpu, memory, disks, network', d.cpu !== undefined && d.mem_total > 0 && 'net_rx' in d && 'disk_rd' in d, d);
  check('no details asked while no panel is open', !asked.some(a => /detail/.test(a)), asked);
  const chip = (await p.$$('#hload .hl'))[0];
  await chip.hover(); await p.waitForTimeout(4000);
  check('pointed at: the details are asked', asked.some(a => /detail=1/.test(a)), asked);
  await p.screenshot({ path: S + 'load-panel.png' });
  await p.mouse.move(5, 900); await p.waitForTimeout(800);
  const n = asked.length; await p.waitForTimeout(3500);
  check('closed: only the summary again', asked.slice(n).length > 0 && asked.slice(n).every(a => !/detail/.test(a)), asked.slice(n));
  await p.evaluate(() => showMe()); await p.waitForTimeout(1200);
  check('Your account: the pickers', await p.evaluate(() => document.querySelectorAll('#modal .pal-card').length >= 10), null);
  await p.evaluate(() => [...document.querySelectorAll('#modal .pal-card')].find(x => /pills|štítky/.test(x.textContent)).click());
  await p.waitForTimeout(800);
  const pr = await p.evaluate(() => api('whoami').then(d => d.who.prefs));
  check('a look picked is kept with the account', pr.hload === 'pills', pr);
  await p.screenshot({ path: S + 'load-pickers.png' });
  await p.evaluate(() => api('prefs', {hload: null}));
  console.log('page errors:', errs.join(' | ') || 'none');
  console.log(ok + ' ok, ' + bad + ' failed');
  await b.close();
})();
